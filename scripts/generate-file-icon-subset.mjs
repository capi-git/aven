#!/usr/bin/env node
// Regenerates src/chrome/fileIconSubset.ts: the Material icon SVGs for common
// files and folders, so the file icons most projects show render without
// loading the full ~1 MB icon set. Run after updating react-material-icon-theme:
//   node scripts/generate-file-icon-subset.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  getFileIcon,
  getFolderIcon,
  getIconSvg,
} from "react-material-icon-theme";

const FILE_NAMES = [
  "agents.md",
  "cargo.lock",
  "cargo.toml",
  "changelog.md",
  "claude.md",
  "dockerfile",
  "index.html",
  "license",
  "license.md",
  "makefile",
  "package-lock.json",
  "package.json",
  "readme.md",
  "tsconfig.json",
  "vite.config.ts",
  ".editorconfig",
  ".env",
  ".gitattributes",
  ".gitignore",
  ".npmrc",
  ".prettierrc",
];

const EXTENSIONS = [
  "astro", "bash", "c", "cc", "cjs", "conf", "cpp", "cs", "css", "csv",
  "d.ts", "dart", "env", "gif", "go", "graphql", "h", "hpp", "htm", "html",
  "ico", "ini", "java", "jpeg", "jpg", "js", "json", "jsonc", "jsx", "kt",
  "less", "lock", "log", "lua", "md", "mdx", "mjs", "mm", "mts", "php", "plist",
  "png", "ps1", "py", "rb", "rs", "scss", "sh", "sql", "svelte", "svg",
  "swift", "test.ts", "test.tsx", "toml", "ts", "tsx", "txt", "vue", "wasm",
  "webp", "xml", "yaml", "yml", "zip", "zsh",
];

const FOLDERS = [
  ".git", ".github", ".vscode", "api", "app", "assets", "bin", "build",
  "chrome", "components", "config", "dist", "docs", "examples", "hooks",
  "icons", "images", "lib", "node_modules", "pages", "public", "scripts",
  "src", "styles", "surfaces", "target", "test", "tests", "utils", "vendor",
];

// Mirrors FileTypeIcon's lookup: full name first, then compound extensions.
function fileIconName(fileName) {
  const key = fileName.toLowerCase();
  const fromName = getFileIcon({ fileName: key, fallback: "", iconPack: "" });
  if (fromName) return fromName;
  const parts = key.split(".");
  const start = parts[0] === "" ? 1 : 0;
  for (let i = start + 1; i < parts.length; i++) {
    const fromExt = getFileIcon({
      fileExtension: parts.slice(i).join("."),
      fallback: "",
      iconPack: "",
    });
    if (fromExt) return fromExt;
  }
  return "file";
}

const names = new Set([
  "file",
  "folder",
  "folder-open",
  "folder-root",
  "folder-root-open",
]);
for (const name of FILE_NAMES) names.add(fileIconName(name));
for (const ext of EXTENSIONS) names.add(fileIconName(`file.${ext}`));
for (const folderName of FOLDERS) {
  for (const isOpen of [false, true]) {
    for (const isRoot of [false, true]) {
      names.add(getFolderIcon({ folderName, isOpen, isRoot }));
    }
  }
}

const entries = [...names].sort().map((name) => {
  const svg = getIconSvg(name);
  if (!svg) throw new Error(`No SVG for icon "${name}"`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`;
});

const source = `// Generated by scripts/generate-file-icon-subset.mjs. Do not edit by hand.
// Material Icon Theme SVGs (MIT) for common files and folders.

export const FILE_ICON_SVGS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;

const out = fileURLToPath(
  new URL("../src/chrome/fileIconSubset.ts", import.meta.url),
);
writeFileSync(out, source);
console.log(`Wrote ${names.size} icons (${source.length} bytes) to ${out}`);
